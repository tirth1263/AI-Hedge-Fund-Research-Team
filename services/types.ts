/**
 * Shared domain types for the AI Hedge Fund workflow.
 *
 * These types are used by the Motia steps (backend) *and* by the web
 * dashboard in `/web`, so the data contract stays identical everywhere.
 */

export type AnalysisType = 'general' | 'fundamental' | 'portfolio' | 'risk' | 'technical'

export type SpecialistType = Exclude<AnalysisType, 'general'>

export const SPECIALISTS: SpecialistType[] = ['fundamental', 'portfolio', 'risk', 'technical']

export type StepStatus = 'completed' | 'failed' | 'skipped'

/* ----------------------------- Web search ----------------------------- */

export interface SearchResult {
  title: string
  link: string
  snippet: string
  source?: string
  date?: string
}

export interface WebSearchData {
  query: string
  status: StepStatus
  results: SearchResult[]
  news: SearchResult[]
  error?: string
  timestamp: string
}

/* ---------------------------- Finance data ---------------------------- */

export interface Quote {
  symbol: string
  price: number
  open: number
  high: number
  low: number
  previousClose: number
  change: number
  changePercent: number
  volume: number
  latestTradingDay: string
}

export interface CompanyOverview {
  symbol: string
  name: string
  description?: string
  exchange?: string
  currency?: string
  sector?: string
  industry?: string
  marketCap?: number
  peRatio?: number
  forwardPE?: number
  pegRatio?: number
  priceToBook?: number
  priceToSales?: number
  eps?: number
  dividendYield?: number
  profitMargin?: number
  operatingMargin?: number
  returnOnEquity?: number
  revenueTTM?: number
  revenueGrowthYoY?: number
  earningsGrowthYoY?: number
  beta?: number
  week52High?: number
  week52Low?: number
  movingAverage50?: number
  movingAverage200?: number
  analystTargetPrice?: number
}

export interface PricePoint {
  date: string
  open: number
  high: number
  low: number
  close: number
  volume: number
}

export interface TechnicalIndicators {
  sma20?: number
  sma50?: number
  ema12?: number
  ema26?: number
  macd?: number
  rsi14?: number
  bollingerUpper?: number
  bollingerLower?: number
  annualizedVolatility?: number
  return1M?: number
  return3M?: number
  maxDrawdown?: number
  valueAtRisk95?: number
  support?: number
  resistance?: number
  trend?: 'uptrend' | 'downtrend' | 'sideways'
}

export interface FinanceData {
  query: string
  symbol: string | null
  status: StepStatus
  quote?: Quote
  overview?: CompanyOverview
  history: PricePoint[]
  indicators?: TechnicalIndicators
  error?: string
  warnings: string[]
  timestamp: string
}

/* ------------------------------ Analyses ------------------------------ */

export interface AnalysisSection {
  type: AnalysisType
  title: string
  status: StepStatus
  summary: string
  details: string
  model?: string
  durationMs?: number
  error?: string
  timestamp: string
}

export type Rating = 'Strong Buy' | 'Buy' | 'Hold' | 'Sell' | 'Strong Sell'

export interface ExecutiveSummary {
  rating: Rating
  confidence: number
  thesis: string
  keyPoints: string[]
  risks: string[]
  timeHorizon: string
}

export interface ComprehensiveReport {
  traceId: string
  query: string
  symbol: string | null
  summary: string
  executiveSummary?: ExecutiveSummary
  sections: Partial<Record<AnalysisType, AnalysisSection>>
  marketData: {
    quote?: Quote
    overview?: CompanyOverview
    indicators?: TechnicalIndicators
    history: PricePoint[]
  }
  sources: SearchResult[]
  completedAnalyses: AnalysisType[]
  failedAnalyses: AnalysisType[]
  disclaimer: string
  timestamp: string
}

export type WorkflowStatus = 'processing' | 'completed' | 'failed'

export interface FinanceResult {
  traceId: string
  status: WorkflowStatus
  query: string
  comprehensiveReport?: ComprehensiveReport
  error?: string
  createdAt: string
  updatedAt: string
}

/* -------------------------- Event payloads ---------------------------- */

export interface QueryReceivedEvent {
  query: string
  timestamp: string
}

export interface CoordinatedData {
  query: string
  webSearch: WebSearchData
  financeData: FinanceData
  timestamp: string
}

export interface SpecialistCompletedEvent {
  type: SpecialistType
  status: StepStatus
}

